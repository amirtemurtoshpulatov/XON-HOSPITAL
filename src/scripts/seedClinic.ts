async function main() {
  const payload = await getPayload({ config: configPromise })
  const chiefSlug = 'xursand-yusupboyevich'
  const existingChief = await payload.find({
    collection: 'doctors', where: { slug: { equals: chiefSlug } }, limit: 1, depth: 0,
  })

  let skipBaseSeed = false
  if (process.env.SEED_MODE === 'if-empty') {
    const [doctorCount, serviceCount] = await Promise.all([
      payload.count({ collection: 'doctors' }),
      payload.count({ collection: 'services' }),
    ])

    if (doctorCount.totalDocs > 0 && serviceCount.totalDocs > 0) {
      skipBaseSeed = true
    }
  }

  if (!existingChief.docs[0]) {
    const chief = doctorProfile('ru', chiefSlug)!
    const record = await payload.create({ collection: 'doctors', locale: 'ru', data: {
      slug: chiefSlug, name: chief.name, specialty: chief.specialty, position: chief.position,
      shortBio: chief.shortBio, instagram: chief.instagram, focusAreas: chief.focusAreas, sortOrder: 1,
    } })
    for (const locale of localeCodes.filter((code) => code !== 'ru')) {
      const profile = doctorProfile(locale, chiefSlug)!
      await payload.update({ collection: 'doctors', id: record.id, locale, data: {
        name: profile.name, specialty: profile.specialty, position: profile.position,
        shortBio: profile.shortBio, focusAreas: profile.focusAreas,
      } })
    }
  }

  if (skipBaseSeed) {
    await seedPreventionArticles(payload)
    payload.logger.info('Clinic seed skipped: database already contains clinic content')
    return
  }

  for (const doctor of doctors) {
    const existing = await payload.find({ collection: 'doctors', where: { slug: { equals: doctor.slug } }, limit: 1 })
    const legacy = !existing.docs[0] && doctor.slug === 'vohid-latipov'
      ? await payload.find({ collection: 'doctors', where: { slug: { equals: 'fohid-latipov' } }, limit: 1 })
      : null
    const existingDoctor = existing.docs[0] || legacy?.docs[0]
    const data = {
      ...doctor,
      focusAreas: doctor.focusAreas.map((label) => ({ label })),
      procedures: doctor.procedures.map((label) => ({ label })),
      verificationStatus: 'needs-review' as const,
      acceptsAppointments: true,
    }
    if (existingDoctor) await payload.update({ collection: 'doctors', id: existingDoctor.id, locale: 'ru', data })
    else await payload.create({ collection: 'doctors', locale: 'ru', data })
  }

  for (const [slug, title, summary, category, featured] of services) {
    const existing = await payload.find({ collection: 'services', where: { slug: { equals: slug } }, limit: 1 })
    const detail = serviceDetails[slug]
    const relatedDoctors = serviceDoctors[slug]?.length
      ? (await payload.find({ collection: 'doctors', where: { slug: { in: serviceDoctors[slug] } }, limit: 20 })).docs.map((doctor) => doctor.id)
      : []
    const data = {
      slug, title, summary, category, featured,
      sortOrder: services.findIndex((item) => item[0] === slug) * 10 + 10,
      doctors: relatedDoctors,
      keyFacts: detail?.keyFacts?.map(([label, value]) => ({ label, value })) || [],
      symptoms: detail?.symptoms?.map((label) => ({ label })) || [],
      conditions: detail?.conditions?.map((label) => ({ label })) || [],
      diagnostics: detail?.diagnostics?.map(([diagnosticTitle, text]) => ({ title: diagnosticTitle, text })) || [],
      advantages: detail?.advantages?.map((label) => ({ label })) || [],
      faq: detail?.faq?.map(([question, answer]) => ({ question, answer })) || [],
    }
    if (existing.docs[0]) await payload.update({ collection: 'services', id: existing.docs[0].id, locale: 'ru', data })
    else await payload.create({ collection: 'services', locale: 'ru', data })
  }

  await seedPreventionArticles(payload)
  payload.logger.info(`Clinic seed complete: ${doctors.length} doctors, ${services.length} services`)
}

main().then(() => process.exit(0)).catch((error) => { console.error(error); process.exit(1) })
